# Builds game/nasa-data.js + docs/data-provenance.json from the team's Earthdata downloads.
# Run: python3 -I build_nasa_data.py <firms_dir> <imerg.h5> <opera_0702.tif> <opera_0705.tif> <out_js> <out_json>
import sys, csv, json, hashlib, collections, os
import numpy as np, h5py, tifffile
firms, imerg, o1, o2, outjs, outjson = sys.argv[1:7]
def sha(p):
    h=hashlib.sha256()
    with open(p,'rb') as f:
        for b in iter(lambda:f.read(1<<20),b''): h.update(b)
    return h.hexdigest()
man=[]
# ---- FIRMS ----
rows=[]
for fn in sorted(os.listdir(firms)):
    if fn.endswith('.csv'):
        p=os.path.join(firms,fn); man.append({'file':fn,'sha256':sha(p),'product':'VIIRS 375 m active fire (FIRMS archive download)','rows':sum(1 for _ in open(p))-1})
        rows+=list(csv.DictReader(open(p)))
def area(lo): return 'W' if lo<-156.55 else ('C' if lo<-156.38 else 'E')
by=collections.defaultdict(list)
for r in rows: by[(r['acq_date'],r['acq_time'].zfill(4),r['satellite'])].append(r)
passes=[];pts=[]
for i,k in enumerate(sorted(by)):
    g=by[k];c=collections.Counter(area(float(r['longitude'])) for r in g);frp=[float(r['frp']) for r in g]
    passes.append({'utc':f"{k[0]}T{k[1][:2]}:{k[1][2:]}Z",'sat':{'N':'Suomi NPP','N20':'NOAA-20','1':'NOAA-20'}.get(k[2],k[2]),'n':len(g),'W':c['W'],'C':c['C'],'E':c['E'],'frpSum':round(sum(frp),1),'frpMax':round(max(frp),1)})
    for r in g: pts.append([round(float(r['latitude']),4),round(float(r['longitude']),4),round(float(r['frp']),1),i])
fr=sorted(float(r['frp']) for r in rows)
F={'event':'Maui, Hawaii, 8-10 August 2023','bbox':[-157.0,20.5,-155.8,21.3],'rows':len(rows),'passes':passes,'points':pts,'frpMedian':fr[len(fr)//2],'frpMax':fr[-1],
   'areaRule':'W: lon < -156.55 · C: -156.55 to -156.38 · E: lon > -156.38 (longitude bands chosen by this project for display, not a NASA classification)'}
# ---- IMERG ----
f=h5py.File(imerg,'r');lon=f['Grid/lon'][:];lat=f['Grid/lat'][:];a=f['Grid/precipitation'][0]
li=np.where((lon>=-90)&(lon<=-78))[0];la=np.where((lat>=18)&(lat<=32))[0]
sub=a[li[0]:li[-1]+1,la[0]:la[-1]+1].astype(float);sub[sub<0]=np.nan
ds=np.nanmean(sub.reshape(60,2,70,2),axis=(1,3))  # 0.2 deg cells, [lon][lat]
im=np.unravel_index(np.nanargmax(sub),sub.shape)
I={'granule':os.path.basename(imerg).split('-',1)[1] if os.path.basename(imerg)[8]=='-' else os.path.basename(imerg),'product':'GPM IMERG Final Run half-hourly V07B (GPM_3IMERGHH)','doi':'10.5067/GPM/IMERG/3B-HH/07',
   'window':'2022-09-27 00:00-00:30 UTC','bbox':[-90,18,-78,32],'units':'mm/hr','cells':int(sub.size),'max':round(float(np.nanmax(sub)),2),'maxAt':[round(float(lat[la[0]+im[1]]),2),round(float(lon[li[0]+im[0]]),2)],
   'mean':round(float(np.nanmean(sub)),2),'fracRain':round(float((sub>=0.1).mean()),3),'fracHeavy':round(float((sub>=10).mean()),4),
   'grid':{'lon0':-90,'lat0':18,'step':0.2,'nx':60,'ny':70,'note':'2x2 mean of the 0.1 degree product, for display only','v':[[round(float(x),1) for x in col] for col in ds]}}
man.append({'file':os.path.basename(imerg),'sha256':sha(imerg),'product':I['product'],'doi':I['doi']})
# ---- OPERA ----
O=[]
for p,d,x0 in ((o1,'2025-07-02',499980),(o2,'2025-07-05',300000)):
    t=tifffile.imread(p);v=int((t!=255).sum())
    O.append({'date':d,'crs':'WGS 84 / UTM zone 14N','pixelM':30,'eastingKm':[x0/1000,(x0+t.shape[1]*30)/1000],'northingKm':[(3500040-t.shape[0]*30)/1000,3500.04],
      'validPx':v,'cloudPct':round(100*float((t==253).sum())/v,1),'clearLandPx':int((t==0).sum()),'waterPx':int((t==1).sum()),'waterKm2':round(float((t==1).sum())*900/1e6,2),'snowIcePx':int((t==252).sum())})
    man.append({'file':os.path.basename(p),'sha256':sha(p),'product':'OPERA L3 DSWx-HLS V1, layer BWTR (binary water)'})
D={'built':'2026-11-15','firms':F,'imerg':I,'opera':{'layer':'BWTR: 0 not water, 1 water, 252 snow/ice, 253 cloud or cloud shadow, 255 no data','files':O,
   'coverageNote':'Kerrville, Hunt and Ingram (Kerr County) fall outside the 2 July mosaic and in the no-data part of the 5 July mosaic, so no before/after flood map of Kerr County can be made from these two files.'}}
open(outjs,'w').write('/* AUTO-GENERATED by tools/build_nasa_data.py from NASA Earthdata downloads. Do not edit by hand. */\n(function(r){const D='+json.dumps(D,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=D;else r.NasaData=D;})(typeof window!=="undefined"?window:globalThis);\n')
json.dump({'built':'2026-11-15','builder':'tools/build_nasa_data.py','sourceFiles':man,'processing':['FIRMS: rows grouped by acq_date+acq_time+satellite; no rows dropped; longitude bands are a display choice','IMERG: precipitation field cut to bbox -90,18,-78,32; 2x2 mean for display; statistics computed on the full 0.1 degree cells','OPERA: pixel counts per class over the whole mosaic; water area = water pixels x 900 m2'],
  'notInGame':'None of these observations changes any score, target or event in the three missions. They are shown as labelled NASA observations in the Final Report and the Data & sources panel.'},open(outjson,'w'),indent=1)
print(json.dumps({k:v for k,v in I.items() if k!='grid'}));print(passes);print(O);print(os.path.getsize(outjs))
